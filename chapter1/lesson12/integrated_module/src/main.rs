// main.rs
mod network {
    // Всё внутри модуля — приватное по умолчанию
    fn private_helper() {
        println!("Это видно только внутри модуля");
    }
    
    // Сделать публичным — ключевое слово `pub`
    pub fn connect() {
        private_helper(); // OK: вызов приватной функции внутри модуля
        println!("Подключение...");
    }
}

fn main() {
    // network::private_helper(); // ОШИБКА: приватная функция
    network::connect();           // OK: публичная функция

    // Вывод:
    // Это видно только внутри модуля
    // Подключение...
}